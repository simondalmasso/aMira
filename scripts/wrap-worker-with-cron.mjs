// Post-build: attach Cloudflare scheduled() to the canonical OpenNext worker.
// The handler performs ONE internal POST to /api/oracle/cron. That route owns
// locking, daily idempotency, durable write acknowledgements, and lifecycle recovery.

import { existsSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OPEN_NEXT_WORKER = resolve(__dirname, '../.open-next/worker.js');
const WRAPPED_WORKER = resolve(__dirname, '../.open-next/worker-with-cron.js');

if (!existsSync(OPEN_NEXT_WORKER)) {
  console.error(`[wrap-worker] ERROR: OpenNext worker not found at ${OPEN_NEXT_WORKER}`);
  process.exit(1);
}

const WRAPPER_CODE = `// AUTO-GENERATED by scripts/wrap-worker-with-cron.mjs
import openNextWorker from './worker.js';

const handler = openNextWorker.default || openNextWorker;
const workerFetch = handler.fetch
  ? handler.fetch.bind(handler)
  : (typeof handler === 'function' ? handler : null);

function bindingsReady(env) {
  return Boolean(
    env?.ORACLE_FCI_HISTORY?.get && env?.ORACLE_FCI_HISTORY?.put &&
    env?.ORACLE_ASSETS_HISTORY?.get && env?.ORACLE_ASSETS_HISTORY?.put &&
    env?.ORACLE_PREDICTIONS?.get && env?.ORACLE_PREDICTIONS?.put
  );
}

export default {
  fetch: workerFetch,

  async scheduled(event, env, ctx) {
    if (!workerFetch) throw new Error('CRON_FETCH_HANDLER_UNAVAILABLE');
    if (!bindingsReady(env)) throw new Error('CRON_BINDINGS_UNAVAILABLE');

    const request = new Request('https://cron.internal/api/oracle/cron', {
      method: 'POST',
      headers: {
        'User-Agent': 'amira-canonical-cron/1.0',
        'X-Internal-Cron': '1',
        'X-Cron-Expression': String(event.cron || ''),
      },
    });
    const response = await workerFetch(request, env, ctx);
    if (!response) throw new Error('CRON_NO_RESPONSE');

    let body;
    try { body = await response.clone().json(); }
    catch { throw new Error('CRON_INVALID_RESPONSE'); }

    const jobs = Array.isArray(body?.jobs) ? body.jobs : [];
    const durable = jobs.length > 0 && jobs.every((job) => job?.ok === true && job?.persistence_ack?.durable === true);
    const lifecycleDurable = body?.lifecycle?.storage === 'durable';
    if (!response.ok || body?.success !== true || !durable || !lifecycleDurable) {
      console.error('[cron] canonical execution failed', {
        status: response.status,
        run_id: body?.run_id ?? null,
        jobs: jobs.map((job) => ({ job: job?.job, ok: job?.ok, durable: job?.persistence_ack?.durable })),
        lifecycle_storage: body?.lifecycle?.storage ?? null,
      });
      throw new Error('CRON_CANONICAL_EXECUTION_FAILED');
    }

    console.log('[cron] canonical execution verified', {
      run_id: body.run_id,
      idempotent_replay: body.idempotent_replay === true,
      jobs: jobs.length,
      lifecycle_storage: body.lifecycle.storage,
    });
  },
};
`;

writeFileSync(WRAPPED_WORKER, WRAPPER_CODE, 'utf-8');
console.log(`[wrap-worker] OK — wrapped worker written to ${WRAPPED_WORKER}`);
console.log('[wrap-worker] Cron handler attached: one canonical POST /api/oracle/cron per scheduled trigger');
