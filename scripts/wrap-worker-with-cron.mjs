// scripts/wrap-worker-with-cron.mjs
// Post-build script: wraps .open-next/worker.js with a `scheduled()` handler
// that runs all 6 V4 cron jobs (refresh_fci, refresh_stocks, refresh_bonds,
// refresh_cedears, refresh_predictions, snapshot_archive).
//
// The wrapper imports the OpenNext default export and re-exports it with the
// additional scheduled handler. Cron expression is configured in wrangler.jsonc
// under triggers.crons = ["0 20 * * 1-5"] (America/Argentina/Buenos_Aires).
//
// Run: `node scripts/wrap-worker-with-cron.mjs` after `opennextjs-cloudflare build`.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OPEN_NEXT_WORKER = resolve(__dirname, '../.open-next/worker.js');
const WRAPPED_WORKER = resolve(__dirname, '../.open-next/worker-with-cron.js');

if (!existsSync(OPEN_NEXT_WORKER)) {
  console.error(`[wrap-worker] ERROR: OpenNext worker not found at ${OPEN_NEXT_WORKER}`);
  console.error(`[wrap-worker] Run \`opennextjs-cloudflare build\` first.`);
  process.exit(1);
}

const WRAPPER_CODE = `// AUTO-GENERATED by scripts/wrap-worker-with-cron.mjs
// Wraps the OpenNext worker with a \`scheduled()\` handler for cron jobs.
// Do not edit by hand — regenerate via \`node scripts/wrap-worker-with-cron.mjs\`.

import openNextWorker from './worker.js';

const handler = openNextWorker.default || openNextWorker;
const workerFetch = handler.fetch
  ? handler.fetch.bind(handler)
  : (typeof handler === 'function' ? handler : null);

// Cron job names per V4 spec.
// FIX_CRON_RECURSION_2026_07_09: removed 'snapshot_archive' from CRON_JOBS.
// Rationale: wrap-worker-with-cron.mjs JOB_ENDPOINTS mapped snapshot_archive →
// /api/oracle/cron, which calls runAllCronJobs() and re-executes all 6 jobs
// in-process (12 runMultiOracle calls per cron trigger instead of 6). Caused
// cron wall clock to balloon to 9.5 min, dangerously close to CF 15-min limit.
// snapshot_archive in cron.ts was a no-op verifier (KV reads only) — its
// absence adds no risk since each refresh_* job already writes its own snapshot.
const CRON_JOBS = [
  'refresh_fci',
  'refresh_stocks',
  'refresh_bonds',
  'refresh_cedears',
  'refresh_predictions',
];

// Internal API endpoints for each cron job
const JOB_ENDPOINTS = {
  refresh_fci: '/api/oracle/fci',
  refresh_stocks: '/api/oracle/stocks',
  refresh_bonds: '/api/oracle/bonds',
  refresh_cedears: '/api/oracle/cedears',
  refresh_predictions: '/api/oracle/predictions',
  snapshot_archive: '/api/oracle/cron',
};

// FIX_CRON_TELEMETRY_BACKTEST (Fix 1):
// Replaced fetch(BASE_URL + path) — CF blocks self-fetch loops against the
// worker's own public URL. Instead we invoke the OpenNext fetch handler
// directly with a synthetic Request. No HTTP round-trip, no recursion.
async function runCronJob(env, ctx, job) {
  const start = Date.now();
  try {
    const path = JOB_ENDPOINTS[job];
    if (!path) {
      console.log('[cron] unknown job:', job);
      return { job, ok: false, error: 'unknown_job', duration_ms: Date.now() - start };
    }
    if (!workerFetch) {
      console.error('[cron] no fetch handler available on OpenNext worker');
      return { job, ok: false, error: 'no_fetch_handler', duration_ms: Date.now() - start };
    }
    const request = new Request('https://cron.internal' + path, {
      method: 'POST',
      headers: {
        'User-Agent': 'santaninverter-oracle-cron/4.0',
        'X-Internal-Cron': '1',
      },
    });
    const res = await workerFetch(request, env, ctx);
    const ok = res ? res.ok : false;
    const status = res ? res.status : 0;
    const duration_ms = Date.now() - start;
    console.log('[cron]', job, '→', status, 'in', duration_ms + 'ms');
    return { job, ok, duration_ms, http_status: status };
  } catch (err) {
    const msg = err instanceof Error ? err.message : String(err);
    console.error('[cron]', job, 'FAILED:', msg);
    return { job, ok: false, error: msg, duration_ms: Date.now() - start };
  }
}

// ─── CRON_PERSISTENCE_VISIBILITY_FIX (minimal instrumentation) ────────────
// Purpose: detect silent cron persistence failure. Before this fix, cron jobs
// could "succeed" (HTTP 200 from internal endpoint) but write nothing to KV
// because the OpenNext handler's process.env.* bindings are not populated
// when called via workerFetch(request, env, ctx) from scheduled().
//
// Approach (additive only, no behavior change to decision engine):
//   1. verifyEnvBindings(env) — log which KV bindings are visible to scheduled()
//   2. countKeys(kv, prefix) — count KV keys before/after each job
//   3. logCronEvent(env, payload) — write structured event to existing
//      telemetry:event:* prefix in ORACLE_PREDICTIONS namespace (NO new
//      namespace, NO new schema field — reuses EventLogEntry.data {}).
//
// All checks are READ-ONLY observations; none alter job execution.

function verifyEnvBindings(env) {
  const bindings = {
    ORACLE_FCI_HISTORY: !!env?.ORACLE_FCI_HISTORY && typeof env.ORACLE_FCI_HISTORY.put === 'function',
    ORACLE_ASSETS_HISTORY: !!env?.ORACLE_ASSETS_HISTORY && typeof env.ORACLE_ASSETS_HISTORY.put === 'function',
    ORACLE_PREDICTIONS: !!env?.ORACLE_PREDICTIONS && typeof env.ORACLE_PREDICTIONS.put === 'function',
  };
  const missing = Object.entries(bindings).filter(([_, v]) => !v).map(([k]) => k);
  return { bindings, missing, allPresent: missing.length === 0 };
}

async function countKeys(kv, prefix) {
  if (!kv || typeof kv.list !== 'function') return -1;
  try {
    const result = await kv.list({ prefix, limit: 1000 });
    return result.keys.length;
  } catch (err) {
    console.error('[cron-persist] countKeys failed for prefix', prefix, err?.message || err);
    return -1;
  }
}

async function logCronEvent(env, payload) {
  // Reuses existing telemetry:event:* prefix in ORACLE_PREDICTIONS namespace.
  // Payload shape matches EventLogEntry (id/timestamp/eventType/source/data/success).
  if (!env?.ORACLE_PREDICTIONS || typeof env.ORACLE_PREDICTIONS.put !== 'function') {
    console.error('[cron-persist] CANNOT LOG EVENT — ORACLE_PREDICTIONS binding missing');
    return;
  }
  const id = 'EVT-CRON-' + Date.now() + '-' + Math.random().toString(36).slice(2, 8);
  const entry = {
    id,
    timestamp: new Date().toISOString(),
    eventType: 'PIPELINE_EXECUTION',
    source: 'scheduled()',
    data: payload,
    success: payload.persistence_verified === true,
  };
  try {
    // TTL 30 days — matches KV_TTL_EVENT_SECONDS in telemetry.ts
    await env.ORACLE_PREDICTIONS.put(
      'telemetry:event:' + id,
      JSON.stringify(entry),
      { expirationTtl: 60 * 60 * 24 * 30 },
    );
  } catch (err) {
    console.error('[cron-persist] logCronEvent KV write failed:', err?.message || err);
  }
}

export default {
  fetch: workerFetch,

  async scheduled(event, env, ctx) {
    const startedAt = new Date().toISOString();
    const jobBatchId = 'cron-' + startedAt.replace(/[:.]/g, '-');
    console.log('[cron] scheduled trigger fired:', event.cron, 'at', startedAt, 'batch:', jobBatchId);

    // ─── CHECK 1: env binding visibility ────────────────────────────────
    const envCheck = verifyEnvBindings(env);
    console.log('[cron-persist] env bindings:', JSON.stringify(envCheck.bindings));
    if (!envCheck.allPresent) {
      console.error('[cron-persist] CRITICAL — missing KV bindings:', envCheck.missing.join(', '),
        '→ cron jobs will execute but persistence will be SILENTLY LOST (MemoryStorageAdapter fallback)');
    }

    // ─── CHECK 2: pre-job KV key counts (baseline) ──────────────────────
    const baseline = {
      fci: await countKeys(env?.ORACLE_FCI_HISTORY, 'snap:'),
      assets: await countKeys(env?.ORACLE_ASSETS_HISTORY, 'snap:'),
      predictions: await countKeys(env?.ORACLE_PREDICTIONS, 'snap:'),
    };
    console.log('[cron-persist] baseline KV counts:', JSON.stringify(baseline));

    // Run all 6 jobs sequentially to avoid KV write contention
    const results = [];
    for (const job of CRON_JOBS) {
      const result = await runCronJob(env, ctx, job);
      results.push(result);
    }

    // ─── CHECK 3: post-job KV key counts (verify writes happened) ───────
    const after = {
      fci: await countKeys(env?.ORACLE_FCI_HISTORY, 'snap:'),
      assets: await countKeys(env?.ORACLE_ASSETS_HISTORY, 'snap:'),
      predictions: await countKeys(env?.ORACLE_PREDICTIONS, 'snap:'),
    };
    const delta = {
      fci: after.fci - baseline.fci,
      assets: after.assets - baseline.assets,
      predictions: after.predictions - baseline.predictions,
    };
    console.log('[cron-persist] post-job KV counts:', JSON.stringify(after));
    console.log('[cron-persist] delta:', JSON.stringify(delta));

    // ─── CHECK 4: structured event log (reuses existing telemetry:event: prefix) ─
    const totalDelta = delta.fci + delta.assets + delta.predictions;
    const persistenceVerified = totalDelta > 0;
    const jobsOk = results.filter(r => r.ok).length;
    const silentFailure = jobsOk > 0 && totalDelta === 0;

    await logCronEvent(env, {
      cron_execution: true,
      job_batch_id: jobBatchId,
      fired_at: startedAt,
      cron_expr: event.cron,
      env_bindings_present: envCheck.allPresent,
      env_bindings_missing: envCheck.missing,
      jobs_total: CRON_JOBS.length,
      jobs_ok: jobsOk,
      jobs_failed: CRON_JOBS.length - jobsOk,
      asset_write_count: totalDelta,
      kv_counts_before: baseline,
      kv_counts_after: after,
      kv_delta: delta,
      persistence_verified: persistenceVerified,
      silent_failure_detected: silentFailure,
      results,
    });

    if (silentFailure) {
      console.error('[cron-persist] SILENT FAILURE DETECTED —',
        jobsOk, 'jobs reported OK but 0 KV writes happened.',
        'Env wiring broken (process.env.* not propagated to OpenNext handler).');
    } else if (persistenceVerified) {
      console.log('[cron-persist] OK —', totalDelta, 'KV writes verified');
    }

    console.log('[cron] all jobs done:', JSON.stringify(results));
  },
};
`;

writeFileSync(WRAPPED_WORKER, WRAPPER_CODE, 'utf-8');
console.log(`[wrap-worker] OK — wrapped worker written to ${WRAPPED_WORKER}`);
// Count jobs dynamically from the generated CRON_JOBS array
const jobCount = (WRAPPER_CODE.match(/'refresh_[a-z]+'/g) || []).length;
console.log(`[wrap-worker] Cron handler attached: scheduled() runs ${jobCount} jobs per trigger`);
